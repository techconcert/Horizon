/**
 * Returns the deterministic daily focus message for any given date.
 * Automatically changes every single day at midnight!
 */
export const getDailyFocusMessage = (
  date: Date = new Date(),
  language: 'English' | 'Español' | 'Português' = 'English'
): string => {
  // Day of the year (0-365) + year seed to give distinct daily rotations
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Combine year and day of year for perpetual variety
  const index = Math.abs((dayOfYear + date.getFullYear() * 13) % DAILY_FOCUS_MESSAGES.length);
  const item = DAILY_FOCUS_MESSAGES[index] || DAILY_FOCUS_MESSAGES[0];
  
  return item[language] || item.English;
};
